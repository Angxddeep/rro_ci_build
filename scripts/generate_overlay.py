"""
Generates Android Runtime Resource Overlay (RRO) source files
from a PixelOS certified_build_props.json file.
"""

import json
import os
import sys

def main():
    json_path = sys.argv[1] if len(sys.argv) > 1 else "certified_build_props.json"
    out_dir = sys.argv[2] if len(sys.argv) > 2 else "overlay"

    if not os.path.isfile(json_path):
        print(f"Error: {json_path} does not exist", file=sys.stderr)
        sys.exit(1)

    with open(json_path, "r", encoding="utf-8") as f:
        props = json.load(f)

    res_values_dir = os.path.join(out_dir, "res", "values")
    os.makedirs(res_values_dir, exist_ok=True)

    items = []
    for k, v in props.items():
        items.append(f"        <item>{k}:{v}</item>")

    arrays_xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by rro_ci_build for PixelOS -->
<resources>
    <string-array name="config_certifiedBuildProperties" translatable="false">
{chr(10).join(items)}
    </string-array>
</resources>
"""

    manifest_xml = """<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    package="co.aospa.android.certifiedprops.overlay"
    android:versionCode="1"
    android:versionName="1.0">

    <application android:hasCode="false"/>
    <overlay android:targetPackage="android"
             android:isStatic="true"
             android:priority="1"/>
</manifest>
"""

    arrays_path = os.path.join(res_values_dir, "arrays.xml")
    manifest_path = os.path.join(out_dir, "AndroidManifest.xml")

    with open(arrays_path, "w", encoding="utf-8") as f:
        f.write(arrays_xml)

    with open(manifest_path, "w", encoding="utf-8") as f:
        f.write(manifest_xml)

    print(f"Successfully generated overlay files in {out_dir}/ from {json_path}")

if __name__ == "__main__":
    main()
